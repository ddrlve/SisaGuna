package com.sisaguna.android.ui.theme

import androidx.compose.ui.unit.dp

/** 3a spacing scale (spec §1.2). [Gutter] is the one left/right page margin for every 3a
 * screen — content never sits off it, even inside full-width bands. */
object SgSpacing {
    val Gutter = 20.dp
    val Xs = 4.dp
    val Sm = 8.dp
    val Md = 12.dp
    val Lg = 16.dp
    val Xl = 24.dp
    val Xxl = 32.dp
}
